"""`archimeter init`: write a commented starter archimeter.toml from what is detected. Read-only on the target."""
from __future__ import annotations

import re
import sys
from collections import Counter
from pathlib import Path

from .config import Config, EventsConfig
from .errors import ArchimeterError
from .extractors.base import Context
from .extractors.event_presets import PRESETS
from .graph import Graph
from .safety import is_secret, walk_sources

HINT_RE = re.compile(r"\b([A-Za-z_][\w]*)\s*\.\s*(publish|emit|subscribe|on|dispatch|trigger|send_event|add_listener|register_handler|listen)\s*\(")


def write_starter(target: str, force: bool) -> None:
    import contextlib
    from .resolve import resolve_target
    import typer
    with contextlib.ExitStack() as stack:
        rt = stack.enter_context(resolve_target(target))
        dest_dir = rt.root if rt.kind in ("path", "build-output") else Path.cwd()
        dest = dest_dir / "archimeter.toml"
        if dest.exists() and not force:
            if sys.stdin.isatty() and typer.confirm(f"{dest} exists. Overwrite?"):
                pass
            else:
                raise ArchimeterError(f"{dest} already exists; pass --force to overwrite it")
        cfg = Config()
        ctx = Context(root=rt.analysis_root, files=[], config=cfg, graph=Graph(), target=dict(rt.identity), kind=rt.mode)
        rt.prepare(ctx)  # for image targets this flattens the image so there is something to inspect
        walk = walk_sources(ctx.root, max_bytes=cfg.analysis.max_file_bytes, skip_vendored=True, extra_deny=[], exclude=cfg.modules.exclude, skip_generated=False)
        files = ctx.files if ctx.files else walk.files
        ctx.files = files
        text = render(ctx, rt)
        dest.write_text(text, encoding="utf-8")
        typer.echo(f"wrote {dest}")


def _detect(ctx: Context) -> dict:
    from .extractors.modules import ModuleDetector
    from .extractors.events import EventExtractor
    langs = Counter(f.lang for f in ctx.files)
    ModuleDetector().extract(ctx)
    mods = Counter(m.removeprefix("module:") for m in ctx.shared["module_of"].values())
    hints: Counter[str] = Counter()
    for f in ctx.files[:4000]:
        if is_secret(f.rel):
            continue
        try:
            for m in HINT_RE.finditer(ctx.read(f)):
                hints[f"{m.group(1)}.{m.group(2)}"] += 1
        except OSError:
            continue
    ctx.config.events = EventsConfig(presets=sorted(PRESETS))
    found: Counter[str] = Counter()
    try:
        EventExtractor().extract(ctx)
        for e in ctx.shared.get("events", {}).get("inventory", []):
            for mech in e["mechanisms"]:
                found[mech] += 1
    except Exception as e:  # detection is advisory; never fail init because of it
        ctx.notes.append(f"event detection failed: {type(e).__name__}")
    return {"langs": langs, "mods": mods, "hints": hints, "found": found}


def render(ctx: Context, rt) -> str:
    d = _detect(ctx)
    presets = sorted(p for p, n in d["found"].items() if p in PRESETS and n)
    top_hints = [(k, n) for k, n in d["hints"].most_common(10) if n >= 3]
    mods = d["mods"].most_common(12)
    lines = [
        "# archimeter.toml: generated by `archimeter init`. Every setting is optional; delete what you do not need.",
        "# Unknown keys are errors, so typos are caught. Docs: README.md, section \"Configuration\".",
        "",
        f"# Detected: {', '.join(f'{n} {l} files' for l, n in d['langs'].most_common()) or 'no source files'}; {len(d['mods'])} modules; target kind: {rt.kind}.",
        "",
        "[modules]",
        "# Directories whose immediate children are modules (e.g. [\"packages\", \"services\"]). Auto-detected when empty.",
        "roots = []",
        "# Group several paths into one module: group = { core = [\"src/core/**\", \"src/shared/**\"] }",
        "group = {}",
        "# Paths excluded from analysis (tests, migrations, vendored or demo data). The default list is shown.",
        "exclude = " + _toml_list(Config().modules.exclude),
        "",
        "[analysis]",
        "# Functions with cyclomatic complexity above this are counted as 'over threshold'.",
        "complexity_threshold = 10",
        "# Skip files marked as generated (@generated, DO NOT EDIT). Always off when analyzing generated applications.",
        "skip_generated = " + ("false" if rt.mode == "generated" else "true"),
        "max_file_bytes = 1000000",
        "",
        "[events]",
        "# Built-in presets: " + ", ".join(sorted(PRESETS)) + ".",
        "# Detected in this target: " + (", ".join(f"{p} ({d['found'][p]} events)" for p in presets) or "none"),
        "presets = " + _toml_list(presets),
        "",
        "# Custom patterns describe your own event bus. `call` matches a dotted suffix (\"bus.publish\" or just \"publish\");",
        "# `arg` is the positional index of the event name, `kwarg` a keyword that takes precedence.",
        "# For decorators use kind = \"decorator\"; name_from = \"function\" uses the decorated function's name.",
    ]
    if top_hints:
        lines.append("# Call names that look like event APIs in this code base (candidates for patterns):")
        lines += [f"#   {k}(...) x{n}" for k, n in top_hints]
        k0 = top_hints[0][0]
        role = "subscribe" if k0.endswith(("subscribe", ".on", "listen", "add_listener", "register_handler")) else "publish"
        lines += ["# [[events.patterns]]", f"# role = \"{role}\"", f"# call = \"{k0}\"", "# arg = 0"]
    else:
        lines += ["# [[events.patterns]]", "# role = \"publish\"", "# call = \"bus.publish\"", "# arg = 0"]
    lines += [
        "",
        "[git]",
        "# Change history window (days before the newest commit) and the largest commit still counted for change coupling.",
        "window_days = 180",
        "max_commit_files = 30",
        "# A module pair is 'hidden coupling' when it co-changes in at least this many commits, with this confidence,",
        "# and has no import or event dependency.",
        "min_support = 3",
        "min_confidence = 0.5",
        "# Flag a module when one author made at least this share of its changes. Authors are hashed unless this is true.",
        "owner_share = 0.7",
        "include_author_names = false",
        "",
        "[image]",
        "# Where application code lives inside container images, when WorkingDir and the entrypoint do not make it clear.",
        "app_paths = " + _toml_list(["/" + r.strip("/") for r in []]),
        "# Platform to select from multi-architecture images.",
        "platform = \"linux/amd64\"",
        "",
        "[provenance]",
        "# Generated applications: path of a provenance manifest (see README), a framework source tree to match files",
        "# against (or pass --framework), and the AST similarity above which a file counts as 'modified from' the framework.",
        "manifest = \"\"",
        "framework = \"\"",
        "similarity_threshold = 0.6",
        "# Modules the customer selected, if the manifest does not say.",
        "selected_modules = []",
        "",
        "[security]",
        "# Extra file patterns that must never be read (the built-in list already covers .env, keys, credentials, databases).",
        "secrets_denylist = []",
        "",
        "[github]",
        "# OAuth App client ID for `archimeter auth login` (device flow). Not a secret. Register your own at",
        "# https://github.com/settings/developers and enable Device Flow.",
        "oauth_client_id = \"\"",
        "",
    ]
    if mods:
        lines.insert(4, "# Largest detected modules: " + ", ".join(f"{m} ({n} files)" for m, n in mods[:8]))
    return "\n".join(lines)


def _toml_list(items: list[str]) -> str:
    import json
    return "[" + ", ".join(json.dumps(i) for i in items) + "]"
